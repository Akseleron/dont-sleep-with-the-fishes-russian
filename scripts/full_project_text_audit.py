def read_tsv(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        return []
    with path.open("r", encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def unescape_xunity(text: str) -> str:
    return text.replace("\\n", "\n").replace("\\r", "\r").replace("\\\\", "\\")


def escape_xunity(text: str) -> str:
    return text.replace("\\", "\\\\").replace("\r", "\\r").replace("\n", "\\n")


def parse_xunity_file(path: Path, known_sources: set[str] | None = None) -> dict[str, str]:
    rows: dict[str, str] = {}
    if not path.exists():
        return rows
    escaped_sources: list[tuple[str, str]] = []
    if known_sources:
        escaped_sources = sorted(
            ((escape_xunity(source), source) for source in known_sources),
            key=lambda item: len(item[0]),
            reverse=True,
        )
    with path.open("r", encoding="utf-8", errors="replace") as handle:
        for raw in handle:
            line = raw.rstrip("\n")
            if not line or line.startswith("#") or "=" not in line:
                continue
            if line.startswith(("r:", "sr:")):
                continue
            matched = False
            for escaped, source in escaped_sources:
                prefix = f"{escaped}="
                if line.startswith(prefix):
                    rows[source] = unescape_xunity(line[len(prefix) :])
                    matched = True
                    break
            if matched:
                continue
            source, target = line.split("=", 1)
            rows[unescape_xunity(source)] = unescape_xunity(target)
    return rows


def load_runtime_dicts(known_sources: set[str]) -> dict[str, str]:
    rows: dict[str, str] = {}
    if not RUNTIME_TEXT_DIR.exists():
        return rows
    for path in sorted(RUNTIME_TEXT_DIR.glob("*.txt")):
        if path.name == "FishingRegex.txt":
            continue
        rows.update(parse_xunity_file(path, known_sources))
    return rows


def has_cyrillic(text: str) -> bool:
    return any("а" <= char.lower() <= "я" or char == "ё" for char in text)


def has_latin(text: str) -> bool:
    return any("A" <= char <= "Z" or "a" <= char <= "z" for char in text)


def normalize(text: str) -> str:
    text = text.replace("’", "'").replace("…", "...")
    text = TAG_RE.sub("", text)
    return re.sub(r"\s+", " ", text).strip().casefold()


def looks_path_or_identifier(text: str) -> bool:
    stripped = text.strip()
    if not stripped:
        return True
    if re.search(r"[\\/][A-Za-z0-9_. -]+[\\/]", stripped):
        return True
    if re.search(r"\.(dll|assets|resource|resS|png|jpg|shader|mat|prefab|asset)\b", stripped, re.I):
        return True
    if re.fullmatch(r"[A-Fa-f0-9]{12,}", stripped):
        return True
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", stripped) and "_" in stripped:
        return True
    if re.fullmatch(r"[A-Za-z0-9_.:+/-]{1,80}", stripped) and "." in stripped and " " not in stripped:
        return True
    if any(word in stripped for word in TECHNICAL_WORDS):
        return True
    return False


def looks_player_facing(text: str) -> bool:
    stripped = text.strip()
    if len(stripped) < 2 or len(stripped) > 700:
        return False
    if not has_latin(stripped):
        return False
    if looks_path_or_identifier(stripped):
        return False
    if WEIGHT_RE.match(stripped) or FOOD_COMPOSITE_RE.match(stripped):
        return True
    if any(term.casefold() in stripped.casefold() for term in CLUSTER_TERMS):
        return True
    if any(mark in stripped for mark in USER_ACTION_HINTS):
        return True
    words = re.findall(r"[A-Za-z][A-Za-z'’.-]*", stripped)
    return len(words) >= 2


def looks_noisy_raw(text: str) -> bool:
    stripped = text.strip()
    if not stripped:
        return True
    if stripped.startswith("[") and ("BepInEx" in stripped or "XUnity" in stripped or "Preloader" in stripped):
        return True
    if stripped.startswith('"') and '";"' in stripped:
        return True
    if stripped[0] in set("!#$%&()*+,./:;<=>?@[\\]^_`{|}~"):
        return True
    letters = sum(1 for char in stripped if char.isalpha())
    ascii_letters = sum(1 for char in stripped if "A" <= char <= "Z" or "a" <= char <= "z")
    symbols = sum(1 for char in stripped if not char.isalnum() and not char.isspace())
    if ascii_letters < 2:
        return True
    if letters / max(len(stripped), 1) < 0.28:
        return True
    if symbols / max(len(stripped), 1) > 0.35:
        return True
    if re.search(r"[!\"#$%&'()*+,./:;<=>?@\[\]\\^_`{|}~-]{8,}", stripped):
        return True
    if re.fullmatch(r"[A-Za-z0-9_() -]{1,80}", stripped) and " " not in stripped and stripped not in CLUSTER_TERMS:
        return True
    if re.fullmatch(r"[A-Za-z0-9_() -]{12,80}", stripped) and " " not in stripped:
        return True
    return False


def raw_candidate_interest(text: str) -> bool:
    if looks_noisy_raw(text):
        return False
    if re.search(r"\bkg\b", text, re.I) and "weight" not in text.casefold() and not re.search(r"\d+(?:\.\d+)?kg\b", text, re.I):
        return False
    cluster_hits = [term for term in CLUSTER_TERMS if term.casefold() in text.casefold() and term != "kg"]
    if cluster_hits:
        return True
    if WEIGHT_RE.match(text) or FOOD_COMPOSITE_RE.match(text):
        return True
    words = re.findall(r"[A-Za-z][A-Za-z'’.-]*", text)
    if len(words) >= 3 and any(mark in text for mark in ["?", "!", "...", "…", ":"]):
        return True
    return False


def clean_raw_ui_candidate(text: str) -> bool:
    stripped = text.strip()
    if not stripped or len(stripped) > 90:
        return False
    if stripped[0].isdigit():
        return False
    if "<br>" in stripped or "\n" in stripped or "\r" in stripped:
        return False
    if any(token in stripped for token in [";", "{", "}", "[", "]", "`", "\\", " -> ", "Base Layer", "AnyState"]):
        return False
    if stripped.startswith(("'", '"')) or stripped.endswith(("'", '"')):
        return False
    if not re.fullmatch(r"[A-Za-z0-9А-Яа-яЁё .,!?:'’+()<>/-]+", stripped):
        return False
    word_tokens = re.findall(r"[A-Za-z]{2,}", stripped)
    if not any(len(token) >= 3 and re.search(r"[AEIOUYaeiouy]", token) for token in word_tokens):
        return False
    if re.fullmatch(r"[A-Za-z_]+ ?\([0-9]+\)(?: [A-Z])?", stripped):
        return False
    if re.fullmatch(r"[A-Za-z_]+(?:_[A-Za-z0-9]+)+", stripped):
        return False
    if "?" in stripped or "!" in stripped or "..." in stripped or "…" in stripped:
        return bool(re.search(r"[A-Za-z]{2,}", stripped))
    if stripped in CLUSTER_TERMS:
        return True
    if re.fullmatch(r"(?:I'm|I am|You|We|The|Try|Give|Pick|Stay|Make|Accept|Use|When|If|Your|Sorry)\b.{2,}", stripped):
        return True
    return False


def likely_technical(text: str, kind: str, context: str) -> bool:
    stripped = text.strip()
    if not stripped or not any(ch.isalpha() for ch in stripped):
        return True
    if not TAG_RE.sub("", stripped).strip() and "<" in stripped and ">" in stripped:
        return True
    if kind == "raw_byte_string":
        if not clean_raw_ui_candidate(stripped):
            return True
        if any(token in stripped for token in ["Base Layer", "AnyState", "Entry ->", " -> "]):
            return True
        if stripped.startswith('"') or stripped.endswith('";"') or '";"' in stripped:
            return True
        if re.fullmatch(r"[A-Za-z_]+ ?\([0-9]+\)(?: [A-Z])?", stripped):
            return True
        if re.fullmatch(r"[A-Za-z_]+[#/\\]?", stripped) and stripped not in CLUSTER_TERMS:
            return True
        if re.fullmatch(r"[A-Za-z_]+[0-9]+(?: \([^)]+\))?", stripped):
            return True
        if re.fullmatch(r"[A-Za-z_]+(?:_[A-Za-z0-9]+)+", stripped):
            return True
        if len(stripped) < 5 and stripped not in CLUSTER_TERMS:
            return True
    if kind in {"GameObject_name_context"}:
        return True
    if looks_path_or_identifier(stripped):
        return True
    lowered = f"{kind} {context}".casefold()
    if any(token in lowered for token in ["shader", "material", "fontasset", "mesh", "spriteatlas"]):
        if not looks_player_facing(stripped):
            return True
    return False


def is_bad_translation_suspect(source: str, target: str) -> tuple[bool, str]:
    if not target:
        return False, ""
    if source == target and looks_player_facing(source):
        return True, "target equals source"
    if has_cyrillic(target) and ENGLISH_WORD_RE.search(TAG_RE.sub(" ", target)):
        return True, f"Russian target contains English-looking fragment: {ENGLISH_WORD_RE.search(target).group(0)}"
    if has_cyrillic(target) and re.search(r"\b[BCDEFGHIJKLMNOPQRSTUVWXYZ]-", target):
        return True, "Latin stutter prefix remains in Russian target"
    source_tags = sorted(TAG_RE.findall(source))
    target_tags = sorted(TAG_RE.findall(target))
    if source_tags != target_tags:
        return True, "TMP/rich text tag mismatch"
    return False, ""


def recursive_strings(value: Any, path: str = "") -> Iterable[tuple[str, str]]:
    if isinstance(value, str):
        yield path, value
    elif isinstance(value, dict):
        for key, item in value.items():
            child = f"{path}.{key}" if path else str(key)
            yield from recursive_strings(item, child)
    elif isinstance(value, (list, tuple)):
        for index, item in enumerate(value):
            child = f"{path}[{index}]"
            yield from recursive_strings(item, child)


def safe_obj_name(obj: Any) -> str:
    try:
        data = obj.read()
        return str(getattr(data, "m_Name", "") or "")
    except Exception:
        try:
            tree = obj.read_typetree(check_read=False)
            return str(tree.get("m_Name", "") or "")
        except Exception:
            return ""


def decode_text_asset_payload(data: Any) -> str:
    payload = getattr(data, "m_Script", b"")
    if isinstance(payload, str):
        return payload
    if isinstance(payload, bytes):
        return payload.decode("utf-8", errors="replace")
    return ""


def scan_unity_file(path: Path) -> list[Candidate]:
    if UnityPy is None or not path.exists():
        return []
    rows: list[Candidate] = []
    try:
        env = UnityPy.load(str(path))
    except Exception:
        return rows

    rel = path.relative_to(ROOT)
    for obj in env.objects:
        type_name = obj.type.name
        name = safe_obj_name(obj)
        base_context = f"asset={rel}; type={type_name}; path_id={obj.path_id}; name={name}"
        if type_name in {"Texture2D", "Sprite"} and name:
            rows.append(Candidate(name, str(rel), f"{type_name}_name", base_context, "unitypy_name"))
            continue

        if type_name == "GameObject" and name:
            rows.append(Candidate(name, str(rel), "GameObject_name_context", base_context, "unitypy_name"))
            continue

        try:
            data = obj.read()
        except Exception:
            data = None

        if type_name == "TextAsset" and data is not None:
            payload = decode_text_asset_payload(data)
            if payload:
                for line_no, text in enumerate(iter_payload_lines(payload), 1):
                    rows.append(
                        Candidate(
                            text,
                            str(rel),
                            "TextAsset_payload",
                            f"{base_context}; line={line_no}",
                            "unitypy_textasset",
                        )
                    )

        if type_name in {"MonoBehaviour", "ScriptableObject"} or type_name.startswith("TextMeshPro"):
            try:
                tree = obj.read_typetree(check_read=False)
            except Exception:
                tree = None
            if tree is not None:
                for field_path, text in recursive_strings(tree):
                    rows.append(
                        Candidate(
                            text,
                            str(rel),
                            f"{type_name}_field",
                            f"{base_context}; field={field_path}",
                            "unitypy_typetree",
                        )
                    )
    return rows


def iter_payload_lines(payload: str) -> Iterable[str]:
    seen: set[str] = set()
    for raw in re.split(r"[\r\n]+", payload):
        text = raw.strip()
        if not text:
            continue
        # CSV-like dialogue rows are useful both as whole rows and field values.
        parts = [part.strip() for part in re.split(r"\t|,(?=(?:[^\"]*\"[^\"]*\")*[^\"]*$)", text)]
        for value in [text, *parts]:
            value = value.strip().strip('"')
            if value and value not in seen:
                seen.add(value)
                yield value


def raw_strings(path: Path) -> list[Candidate]:
    if not path.exists():
        return []
    data = path.read_bytes()
    rel = path.relative_to(ROOT)
    rows: list[Candidate] = []
    for method, regex, decoder in (
        ("raw_ascii", ASCII_RE, lambda raw: raw.decode("utf-8", errors="replace")),
        ("raw_utf16le", UTF16_RE, lambda raw: raw.decode("utf-16le", errors="replace")),
    ):
        hits = 0
        for match in regex.finditer(data):
            text = decoder(match.group(0)).strip()
            if not text or len(text) > 220:
                continue
            if not raw_candidate_interest(text):
                continue
            rows.append(
                Candidate(
                    text,
                    str(rel),
                    "raw_byte_string",
                    f"byte_offset={match.start()}; method={method}",
                    method,
                )
            )
            hits += 1
            if hits >= 1200:
                break
    return rows


