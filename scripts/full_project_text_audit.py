def candidates_from_runtime(known_sources: set[str]) -> list[Candidate]:
    rows: list[Candidate] = []
    for path in sorted(RUNTIME_TEXT_DIR.glob("*.txt")) if RUNTIME_TEXT_DIR.exists() else []:
        if path.name == "FishingRegex.txt":
            for line_no, raw in enumerate(path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
                if raw.strip() and not raw.startswith("#"):
                    rows.append(Candidate(raw, str(path.relative_to(ROOT)), "xunity_regex_rule", f"line={line_no}", "runtime_xunity_regex"))
            continue
        for source, target in parse_xunity_file(path, known_sources).items():
            if not target or source == target or looks_player_facing(source):
                rows.append(
                    Candidate(
                        source,
                        str(path.relative_to(ROOT)),
                        "runtime_xunity_text",
                        f"target={target[:120]}",
                        "runtime_xunity_dictionary",
                    )
                )

    if RUNTIME_LOG.exists():
        log_text = RUNTIME_LOG.read_text(encoding="utf-8", errors="replace")
        for line_no, line in enumerate(log_text.splitlines(), 1):
            if any(term.casefold() in line.casefold() for term in CLUSTER_TERMS | KNOWN_RUNTIME_ISSUES):
                rows.append(
                    Candidate(
                        line.strip()[:500],
                        str(RUNTIME_LOG.relative_to(ROOT)),
                        "runtime_log_line",
                        f"line={line_no}",
                        "runtime_log",
                    )
                )
    if RUNTIME_CONFIG.exists():
        for line_no, line in enumerate(RUNTIME_CONFIG.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            if any(key in line for key in ["OutputUntranslatableText", "EnableTextPathLogging", "TextGetterCompatibilityMode", "IgnoreVirtualTextSetterCallingRules"]):
                rows.append(Candidate(line.strip(), str(RUNTIME_CONFIG.relative_to(ROOT)), "runtime_config", f"line={line_no}", "runtime_config"))
    return rows


def candidates_from_texture_index() -> list[Candidate]:
    rows: list[Candidate] = []
    for row in read_tsv(TEXTURE_INDEX):
        name = row.get("name", "")
        if not name:
            continue
        context = (
            f"type={row.get('type', '')}; path_id={row.get('path_id', '')}; "
            f"size={row.get('width', '')}x{row.get('height', '')}; exported={row.get('exported', '')}"
        )
        rows.append(Candidate(name, row.get("asset_file", ""), "exported_texture_name", context, "texture_index"))
    for term in KNOWN_TEXTURE_TERMS:
        rows.append(Candidate(term, "runtime screenshots / texture export", "known_texture_candidate", "", "manual_known_texture_candidate"))
    return rows


def source_queue_maps() -> tuple[dict[str, dict[str, str]], dict[str, str]]:
    rows = read_tsv(QUEUE)
    by_source = {row.get("source", ""): row for row in rows if row.get("source", "")}
    targets = {row.get("source", ""): row.get("final_russian", "") for row in rows if row.get("source", "")}
    return by_source, targets


def classify_candidate(
    cand: Candidate,
    queue_rows: dict[str, dict[str, str]],
    generated: dict[str, str],
    runtime: dict[str, str],
) -> dict[str, str] | None:
    source = cand.source.strip()
    if not source:
        return None
    if cand.kind == "runtime_log_line" and source.startswith("["):
        return make_row(cand, "", "likely_technical", "low", "", "ignore", "runtime infrastructure log line")

    current_ru = ""
    if source in queue_rows:
        current_ru = queue_rows[source].get("final_russian", "")
    elif source in generated:
        current_ru = generated[source]
    elif source in runtime:
        current_ru = runtime[source]

    queue_row = queue_rows.get(source)
    in_generated = source in generated
    in_runtime = source in runtime

    if cand.kind in {"Texture2D_name", "Sprite_name", "exported_texture_name", "known_texture_candidate"}:
        if source in KNOWN_TEXTURE_TERMS or any(term in source.casefold() for term in ["menu", "button", "journal", "diary", "book", "paper", "page", "note", "junk", "title", "logo", "item", "found"]):
            return make_row(cand, current_ru, "likely_texture_only", "medium", "", "texture_redraw", "texture or sprite name/candidate; requires visual confirmation")
            return make_row(cand, current_ru, "likely_technical", "low", "", "ignore", "texture name does not look player-facing")

    if RICH_WEIGHT_RE.match(source):
        return None

    if WEIGHT_RE.match(source) or "Weight:" in source and "kg" in source:
        return make_row(cand, current_ru, "dynamic_runtime", "high", "Вес: X кг", "runtime_test", "do not solve with exact numeric rows; regex/plugin path must be tested")

    if FOOD_COMPOSITE_RE.match(source):
        return make_row(cand, current_ru, "dynamic_runtime", "medium", "", "runtime_test", "composite fish result; exact dictionary may not cover runtime formatting")

    if likely_technical(source, cand.kind, cand.context):
        return make_row(cand, current_ru, "likely_technical", "low", "", "ignore", "technical/internal-looking string")

    if queue_row:
        status = queue_row.get("status", "")
        if status == "skip":
            return make_row(cand, current_ru, "likely_technical", "low", "", "ignore", "queue row is marked skip")
        if not current_ru:
            return make_row(cand, current_ru, "missing_from_queue", "high", "", "fix_source_queue", "queue row has empty final_russian")
        bad, reason = is_bad_translation_suspect(source, current_ru)
        if bad:
            return make_row(cand, current_ru, "bad_translation_suspect", "medium", "", "fix_source_queue", reason)
        if not in_generated and status == "approved":
            return make_row(cand, current_ru, "in_queue_but_not_dictionary", "high", "", "rebuild_dictionary", "approved queue row is absent from generated dictionary")
        if status == "needs_review":
            return make_row(cand, current_ru, "needs_runtime_check", "medium", "", "runtime_test", "queue row still needs review")
        return make_row(cand, current_ru, "translated", "low", "", "ignore", "covered by source_queue/generated dictionary")

    if source in generated:
        bad, reason = is_bad_translation_suspect(source, generated[source])
        if bad:
            return make_row(cand, generated[source], "bad_translation_suspect", "medium", "", "fix_source_queue", reason)
        return make_row(cand, generated[source], "translated", "low", "", "ignore", "covered by generated dictionary")

    if source in runtime:
        return make_row(cand, runtime[source], "needs_runtime_check", "medium", "", "add_to_source_queue", "seen in runtime XUnity files but absent from source queue")

    if looks_player_facing(source):
        severity = "high" if any(term.casefold() in source.casefold() for term in CLUSTER_TERMS) else "medium"
        return make_row(cand, current_ru, "missing_from_queue", severity, "", "add_to_source_queue", "likely player-facing English source not covered")

    return make_row(cand, current_ru, "likely_technical", "low", "", "ignore", "low-confidence/non-player-facing candidate")


def make_row(
    cand: Candidate,
    current_ru: str,
    category: str,
    severity: str,
    proposed_fix: str,
    action: str,
    notes: str,
) -> dict[str, str]:
    return {
        "source": cand.source.strip(),
        "current_ru": current_ru,
        "location": cand.location,
        "kind": cand.kind,
        "context": cand.context,
        "category": category,
        "severity": severity,
        "proposed_fix": proposed_fix,
        "action": action,
        "notes": f"{notes}; method={cand.method}",
    }


def add_queue_quality_rows(rows: list[dict[str, str]], queue_rows: dict[str, dict[str, str]], generated: dict[str, str]) -> None:
    rich_weight_sources = [source for source in queue_rows if RICH_WEIGHT_RE.match(source)]
    if rich_weight_sources:
        rows.append(
            {
                "source": "<b>Weight:</b> Nkg exact range",
                "current_ru": f"{len(rich_weight_sources)} rows",
                "location": "translations/source_queue.tsv",
                "kind": "source_queue_aggregate",
                "context": "rich exact numeric Weight rows remain after plain Weight cleanup",
                "category": "dynamic_runtime",
                "severity": "high",
                "proposed_fix": "remove exact rich Weight range rows after confirming regex/plugin path",
                "action": "fix_source_queue",
                "notes": "do not regenerate numeric Weight ranges",
            }
        )

    for source, row in queue_rows.items():
        target = row.get("final_russian", "")
        status = row.get("status", "")
        if status == "skip":
            continue
        if not target:
            rows.append(make_row(Candidate(source, "translations/source_queue.tsv", row.get("kind", ""), row.get("context", ""), "source_queue"), target, "missing_from_queue", "high", "", "fix_source_queue", "empty final_russian"))
            continue
        if status == "needs_review":
            rows.append(make_row(Candidate(source, "translations/source_queue.tsv", row.get("kind", ""), row.get("context", ""), "source_queue"), target, "needs_runtime_check", "medium", "", "runtime_test", "queue row still needs review"))
        bad, reason = is_bad_translation_suspect(source, target)
        if bad:
            rows.append(make_row(Candidate(source, "translations/source_queue.tsv", row.get("kind", ""), row.get("context", ""), "source_queue"), target, "bad_translation_suspect", "medium", "", "fix_source_queue", reason))
        if status == "approved" and source not in generated:
            rows.append(make_row(Candidate(source, "translations/source_queue.tsv", row.get("kind", ""), row.get("context", ""), "source_queue"), target, "in_queue_but_not_dictionary", "high", "", "rebuild_dictionary", "approved row absent from generated dictionary"))

    for row in read_tsv(QUALITY_REPORT):
        rows.append(
            {
                "source": row.get("source", ""),
                "current_ru": row.get("final_russian", ""),
                "location": "extracted/translation_quality_report.tsv",
                "kind": row.get("kind", ""),
                "context": row.get("context", ""),
                "category": "bad_translation_suspect",
                "severity": "medium",
                "proposed_fix": "",
                "action": "fix_source_queue",
                "notes": f"{row.get('issue_type', '')}: {row.get('evidence', '')}",
            }
        )

    for row in read_tsv(JOURNAL_FIT_REPORT):
        risk = row.get("risk_level", "")
        if risk in {"high", "medium"}:
            rows.append(
                {
                    "source": row.get("source", ""),
                    "current_ru": row.get("final_russian", ""),
                    "location": "extracted/journal_fit_report.tsv",
                    "kind": row.get("kind", ""),
                    "context": f"estimated_total_lines={row.get('estimated_total_lines', '')}; source_length={row.get('source_length', '')}; final_length={row.get('final_length', '')}",
                    "category": "bad_translation_suspect",
                    "severity": "medium" if risk == "high" else "low",
                    "proposed_fix": "",
                    "action": "fix_source_queue",
                    "notes": f"journal layout risk={risk}; {row.get('notes', '')}",
                }
            )


def dedupe_rows(rows: list[dict[str, str]]) -> list[dict[str, str]]:
    priority = {"high": 0, "medium": 1, "low": 2}
    category_priority = {
        "dynamic_runtime": 0,
        "missing_from_queue": 1,
        "in_queue_but_not_dictionary": 2,
        "bad_translation_suspect": 3,
        "needs_runtime_check": 4,
        "likely_texture_only": 5,
        "translated": 6,
        "likely_technical": 7,
    }
    best: dict[tuple[str, str, str], dict[str, str]] = {}
    for row in rows:
        source = row.get("source", "")
        if not source:
            continue
        key = (source, row.get("category", ""), row.get("action", ""))
        existing = best.get(key)
        if existing is None:
            best[key] = row
            continue
        current_rank = (priority.get(row.get("severity", "low"), 9), category_priority.get(row.get("category", ""), 9), len(row.get("context", "")))
        existing_rank = (priority.get(existing.get("severity", "low"), 9), category_priority.get(existing.get("category", ""), 9), len(existing.get("context", "")))
        if current_rank < existing_rank:
            best[key] = row

    filtered = list(best.values())
    filtered.sort(
        key=lambda row: (
            priority.get(row.get("severity", "low"), 9),
            category_priority.get(row.get("category", ""), 9),
            row.get("source", "").casefold(),
        )
    )
    return filtered


def write_tsv(path: Path, rows: list[dict[str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=AUDIT_FIELDS, delimiter="\t", lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def write_markdown(path: Path, rows: list[dict[str, str]], queue_rows: dict[str, dict[str, str]], generated: dict[str, str]) -> None:
    category_counts = Counter(row["category"] for row in rows)
    severity_counts = Counter(row["severity"] for row in rows)
    needs_review = [row for row in queue_rows.values() if row.get("status") == "needs_review"]
    journal_needs = [row for row in needs_review if row.get("kind", "").startswith("resource_textasset_journal")]
    plain_weight_rows = [source for source in queue_rows if source.startswith("Weight: ")]
    rich_weight_rows = [source for source in queue_rows if RICH_WEIGHT_RE.match(source)]
    quality_findings = read_tsv(QUALITY_REPORT)
    journal_findings = read_tsv(JOURNAL_FIT_REPORT)

    def table(title: str, selected: list[dict[str, str]], limit: int = 40) -> list[str]:
        lines = [f"\n## {title}\n", "| source | current ru | location | category | severity | action | notes |", "|---|---|---|---|---|---|---|"]
        for row in selected[:limit]:
            lines.append(
                "| "
                + " | ".join(
                    md_cell(row.get(field, ""))
                    for field in ["source", "current_ru", "location", "category", "severity", "action", "notes"]
                )
                + " |"
            )
        if len(selected) > limit:
            lines.append(f"\n_... {len(selected) - limit} more rows in TSV._")
        return lines

    high_missing = [row for row in rows if row["category"] == "missing_from_queue" and row["severity"] in {"high", "medium"}]
    textures = [row for row in rows if row["category"] == "likely_texture_only"]
    dynamic = [row for row in rows if row["category"] == "dynamic_runtime"]
    bad = [row for row in rows if row["category"] == "bad_translation_suspect"]
    review = [row for row in rows if row["category"] == "needs_runtime_check"]

    lines = [
        "# Full project text audit",
        "",
        "## Current State",
        "",
        f"- active generated translations: {len(generated)}",
        f"- needs_review count: {len(needs_review)}",
        f"- journal needs_review count: {len(journal_needs)}",
        f"- plain Weight rows left: {len(plain_weight_rows)}",
        f"- rich exact Weight rows left: {len(rich_weight_rows)}",
        f"- quality findings count: {len(quality_findings)}",
        f"- journal fit findings count: {len(journal_findings)}",
        f"- audit TSV rows: {len(rows)}",
        "",
        "## Category Counts",
        "",
    ]
    lines.extend(f"- {key}: {value}" for key, value in sorted(category_counts.items()))
    lines.extend(["", "## Severity Counts", ""])
    lines.extend(f"- {key}: {value}" for key, value in sorted(severity_counts.items()))

    lines.extend(
        [
            "",
            "## Summary",
            "",
            "- This is a report-only audit. It does not edit `translations/source_queue.tsv`.",
            "- Plain `Weight: Xkg` rows are still absent, as expected.",
            "- Rich exact `<b>Weight:</b> Xkg` rows are reported separately if present.",
            "- `FishingRegex.txt` remains a runtime hypothesis until the game proves it applies.",
        ]
    )
    lines.extend(table("Top Missing User-Facing Candidates", high_missing))
    lines.extend(table("Dynamic Runtime Issues", dynamic, 30))
    lines.extend(table("Likely Texture-Only Candidates", textures, 30))
    lines.extend(table("Bad Translation Suspects", bad, 60))
    lines.extend(table("Needs Runtime Check", review, 40))
    lines.extend(
        [
            "",
            "## Recommended Next Small Commit",
            "",
            "1. Remove remaining rich exact `<b>Weight:</b> ...kg` rows if approved, then rebuild and validate.",
            "2. Add high-confidence missing event/action strings from `extracted/missing_translation_candidates.tsv`.",
            "3. Fix obvious bad translation suspects from `extracted/bad_translation_suspects.tsv`.",
            "4. Runtime-test `FishingRegex.txt`; if it does not apply, implement a minimal fishing formatter plugin later.",
            "5. Keep texture redraw work separate using the texture export/candidate reports.",
        ]
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def md_cell(text: str) -> str:
    text = re.sub(r"\s+", " ", str(text)).strip()
    text = text.replace("|", "\\|")
    if len(text) > 140:
        text = text[:137] + "..."
    return text


def main() -> int:
    queue_rows, _queue_targets = source_queue_maps()
    known_sources = set(queue_rows)
    generated = parse_xunity_file(GENERATED_DICT, known_sources)
    runtime = load_runtime_dicts(known_sources)

    candidates: list[Candidate] = []
    candidates.extend(candidates_from_existing_tables())
    candidates.extend(candidates_from_runtime(known_sources))
    candidates.extend(candidates_from_texture_index())

    for path in ASSET_FILES:
        candidates.extend(scan_unity_file(path))
        candidates.extend(raw_strings(path))

    audit_rows: list[dict[str, str]] = []
    for cand in candidates:
        row = classify_candidate(cand, queue_rows, generated, runtime)
        if row is not None:
            audit_rows.append(row)

    add_queue_quality_rows(audit_rows, queue_rows, generated)
    audit_rows = dedupe_rows(audit_rows)

    user_facing = [row for row in audit_rows if row["category"] not in {"likely_technical", "translated"}]
    missing = [row for row in audit_rows if row["category"] == "missing_from_queue"]
    bad = [row for row in audit_rows if row["category"] == "bad_translation_suspect"]
    textures = [row for row in audit_rows if row["category"] == "likely_texture_only"]

    write_tsv(DEBUG_TSV, audit_rows)
    write_tsv(USER_FACING_TSV, user_facing)
    write_tsv(MISSING_TSV, missing)
    write_tsv(BAD_TSV, bad)
    write_tsv(TEXTURE_TSV, textures)
    write_markdown(DEBUG_MD, audit_rows, queue_rows, generated)

    print(f"wrote {len(audit_rows)} audit rows to {DEBUG_TSV.relative_to(ROOT)}")
    print(f"wrote {len(user_facing)} user-facing rows to {USER_FACING_TSV.relative_to(ROOT)}")
    print(f"wrote {len(missing)} missing rows to {MISSING_TSV.relative_to(ROOT)}")
    print(f"wrote {len(bad)} bad-translation rows to {BAD_TSV.relative_to(ROOT)}")
    print(f"wrote {len(textures)} texture rows to {TEXTURE_TSV.relative_to(ROOT)}")
    print(f"wrote markdown report to {DEBUG_MD.relative_to(ROOT)}")
    return 0


